"""
RX-only APRS iGate on an RTL-SDR dongle: rtl_fm | direwolf as a systemd user service.

rtl_fm tunes the dongle and pipes FM-demodulated audio to Dire Wolf, which
decodes AFSK 1200 and, with the iGate on, forwards packets to APRS-IS and
beacons the iGate position there (never over RF: an RTL-SDR cannot transmit).
Dire Wolf also serves the decoded frames on a KISS TCP port; the gateway
daemon reads them (aprs_monitor in gateway.py) for the APRS tab.

Like the TNC services (bpq_services.py), the unit file lives in
~/.config/systemd/user and is enabled for start at boot, which needs
lingering for the account (`sudo loginctl enable-linger ok2zaw`).
"""

import os
import re
import shutil

from radio_apps import RadioError, is_active, systemctl, unit_log, unit_status

UNIT = "meshcom-aprs.service"
UNIT_DIR = os.path.join(os.path.expanduser("~"), ".config", "systemd", "user")
CONFIG_DIR = os.path.join(os.path.expanduser("~"), ".config", "meshcom")
DIREWOLF_CONFIG = os.path.join(CONFIG_DIR, "direwolf-aprs.conf")
HEADER = "# Generated by the MeshCom gateway web UI (APRS tab); changes are overwritten."
SAMPLE_RATE = 24000
MAX_DELAY_SECONDS = 600
DEFAULT_SERVER = "euro.aprs2.net"

_CALLSIGN = re.compile(r"^[A-Z0-9]{3,6}(-([0-9]|1[0-5]))?$")
_HOST = re.compile(r"^[A-Za-z0-9.-]{1,253}(:[0-9]{1,5})?$")
_DEVICE = re.compile(r"^[A-Za-z0-9_-]{1,32}$")
_COMMENT = re.compile(r'^[^"\\\r\n]{0,60}$')


def passcode(callsign: str) -> int:
    """APRS-IS passcode of a callsign (public hash of the base call, SSID ignored)."""
    call = callsign.upper().split("-")[0]
    value = 0x73E2
    for index in range(0, len(call), 2):
        value ^= ord(call[index]) << 8
        if index + 1 < len(call):
            value ^= ord(call[index + 1])
    return value & 0x7FFF


def _number(cfg: dict, key: str, label: str, minimum: float, maximum: float, integer: bool = False):
    raw = str(cfg.get(key, "")).strip().replace(",", ".")
    try:
        value = int(raw) if integer else float(raw)
    except ValueError:
        raise RadioError(f"{label} musí být {'celé ' if integer else ''}číslo.") from None
    if not minimum <= value <= maximum:
        raise RadioError(f"{label} musí být v rozsahu {minimum:g} až {maximum:g}.")
    return value


def settings(cfg: dict, own_position: dict | None = None) -> dict:
    """Validated APRS settings; raises RadioError with a message for the web form."""
    call = str(cfg.get("aprs_callsign", "")).strip().upper()
    if not _CALLSIGN.match(call):
        raise RadioError("APRS: zadejte volací značku iGate, např. OK2ZAW-1 (SSID 0–15).")
    raw_pass = str(cfg.get("aprs_passcode", "")).strip()
    if raw_pass and not (raw_pass.isdigit() and int(raw_pass) <= 32767):
        raise RadioError("APRS: passcode je číslo 0–32767 (prázdné = vypočítat ze značky).")
    device = str(cfg.get("aprs_device", "0")).strip() or "0"
    if not _DEVICE.match(device):
        raise RadioError("APRS: index nebo sériové číslo RTL-SDR smí obsahovat jen písmena, číslice, - a _.")
    gain_raw = str(cfg.get("aprs_gain", "")).strip()
    result = {
        "callsign": call,
        "passcode": int(raw_pass) if raw_pass else passcode(call),
        "frequency_hz": int(round(_number(cfg, "aprs_frequency_mhz", "APRS: kmitočet (MHz)", 24, 1766) * 1e6)),
        "gain": _number(cfg, "aprs_gain", "APRS: zisk (dB)", 0, 50) if gain_raw else None,
        "ppm": _number(cfg, "aprs_ppm", "APRS: korekce kmitočtu (ppm)", -200, 200, integer=True),
        "device": device,
        "kiss_port": _number(cfg, "aprs_kiss_port", "APRS: KISS port", 1024, 65535, integer=True),
        "igate": bool(cfg.get("aprs_igate")),
        "beacon": bool(cfg.get("aprs_beacon")),
        "server": str(cfg.get("aprs_server", "")).strip() or DEFAULT_SERVER,
        "comment": str(cfg.get("aprs_comment", "")).strip(),
        "latitude": None,
        "longitude": None,
        "position_source": None,   # "form", "manual" (map pick) or "node" (node beacon)
    }
    if not _HOST.match(result["server"]):
        raise RadioError("APRS: server APRS-IS zadejte jako host nebo host:port.")
    if not _COMMENT.match(result["comment"]):
        raise RadioError("APRS: komentář majáku má nejvýš 60 znaků a nesmí obsahovat uvozovky ani \\.")
    if str(cfg.get("aprs_latitude", "")).strip() or str(cfg.get("aprs_longitude", "")).strip():
        result["latitude"] = _number(cfg, "aprs_latitude", "APRS: zeměpisná šířka", -90, 90)
        result["longitude"] = _number(cfg, "aprs_longitude", "APRS: zeměpisná délka", -180, 180)
        result["position_source"] = "form"
    elif own_position:
        # Same point the RF stations map uses: the position picked there, else the node beacon.
        result["latitude"], result["longitude"] = own_position["latitude"], own_position["longitude"]
        result["position_source"] = own_position.get("source", "node")
    # Without any position the iGate still runs, it only does not beacon (see beacon_active).
    return result


def configured_position(cfg: dict) -> dict | None:
    """Position typed on the APRS tab, or None when it is empty or invalid (never raises)."""
    try:
        latitude = float(str(cfg.get("aprs_latitude", "")).strip().replace(",", "."))
        longitude = float(str(cfg.get("aprs_longitude", "")).strip().replace(",", "."))
    except ValueError:
        return None
    if not (-90 <= latitude <= 90 and -180 <= longitude <= 180):
        return None
    return {"latitude": latitude, "longitude": longitude, "source": "aprs"}


def beacon_active(values: dict) -> bool:
    return bool(values["igate"] and values["beacon"] and values["latitude"] is not None)


def direwolf_config(values: dict) -> str:
    """Dire Wolf configuration: audio comes from stdin (rtl_fm), nothing is transmitted."""
    lines = [
        HEADER,
        "# Audio is read from stdin (the trailing '-' on the command line); no audio output.",
        "ADEVICE null null",
        "ACHANNELS 1",
        "CHANNEL 0",
        f"MYCALL {values['callsign']}",
        "MODEM 1200",
        f"KISSPORT {values['kiss_port']}",
    ]
    if values["igate"]:
        lines += [
            "",
            "# RX-only iGate: RF -> APRS-IS. Without IGTXVIA nothing goes back to RF.",
            f"IGSERVER {values['server']}",
            f"IGLOGIN {values['callsign']} {values['passcode']}",
        ]
        if beacon_active(values):
            comment = values["comment"] or "RX iGate (RTL-SDR)"
            lines.append(
                f"PBEACON sendto=IG delay=1 every=30 overlay=R symbol=\"igate\" "
                f"lat={values['latitude']:.5f} long={values['longitude']:.5f} comment=\"{comment}\"")
    return "\n".join(lines) + "\n"


def command(values: dict) -> str:
    """Shell pipeline for ExecStart; every value is validated, so no quoting is needed."""
    rtl_fm = ["rtl_fm", "-d", values["device"], "-f", str(values["frequency_hz"]), "-M", "fm",
              "-s", str(SAMPLE_RATE), "-E", "dc", "-p", str(values["ppm"])]
    if values["gain"] is not None:
        rtl_fm += ["-g", f"{values['gain']:g}"]
    direwolf = ["direwolf", "-c", DIREWOLF_CONFIG, "-t", "0", "-r", str(SAMPLE_RATE), "-"]
    return f"{' '.join(rtl_fm)} - | {' '.join(direwolf)}"


def _delay(cfg: dict) -> int:
    try:
        return max(0, min(int(cfg.get("aprs_delay", 0)), MAX_DELAY_SECONDS))
    except (TypeError, ValueError):
        return 0


def unit_content(values: dict, cfg: dict) -> str:
    if " " in DIREWOLF_CONFIG:
        raise RadioError("Cesta k domovskému adresáři nesmí obsahovat mezery.")
    delay = _delay(cfg)
    lines = [HEADER, "[Unit]", "Description=MeshCom APRS RX iGate (RTL-SDR + Dire Wolf)", "",
             "[Service]", "Type=simple"]
    if delay:
        lines.append(f"ExecStartPre=/bin/sleep {delay}")
    lines += [
        f"ExecStart=/bin/sh -c '{command(values)}'",
        # rtl_fm ends when the dongle is unplugged; Dire Wolf then sees EOF and exits cleanly.
        "Restart=always",
        "RestartSec=15",
        f"TimeoutStartSec={delay + 90}",
        "",
        "[Install]",
        "WantedBy=default.target",
        "",
    ]
    return "\n".join(lines)


def missing_programs() -> list[str]:
    return [name for name in ("rtl_fm", "direwolf") if shutil.which(name) is None]


def _write(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp_path = path + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as handle:
        handle.write(content)
    os.replace(tmp_path, path)


def unit_path() -> str:
    return os.path.join(UNIT_DIR, UNIT)


def write_unit(cfg: dict, own_position: dict | None = None) -> None:
    """Write (or remove when disabled) the service and Dire Wolf config; raises RadioError."""
    path = unit_path()
    if not cfg.get("aprs_enabled"):
        if os.path.exists(path):
            systemctl("disable", "--now", UNIT, check=False)
            os.remove(path)
            systemctl("daemon-reload")
        return
    values = settings(cfg, own_position)
    _write(DIREWOLF_CONFIG, direwolf_config(values))
    _write(path, unit_content(values, cfg))
    systemctl("daemon-reload")
    systemctl("enable" if cfg.get("aprs_autostart") else "disable", UNIT, check=False)


def _require_unit() -> None:
    if not os.path.exists(unit_path()):
        raise RadioError("Služba není vytvořená; zapněte APRS příjem a uložte nastavení.")


def start() -> bool:
    _require_unit()
    if is_active(UNIT):
        return False
    systemctl("start", "--no-block", UNIT)
    return True


def stop() -> None:
    _require_unit()
    systemctl("stop", UNIT)


def restart() -> None:
    _require_unit()
    systemctl("restart", "--no-block", UNIT)


def status() -> dict:
    return unit_status(UNIT)


def recent_log(lines: int = 30) -> str:
    return unit_log(UNIT, lines)


def igate_state(log: str) -> str | None:
    """Last APRS-IS connection event Dire Wolf logged: "connected", "disconnected" or None."""
    state = None
    for line in log.splitlines():
        lowered = line.lower()
        if "now connected to igate server" in lowered:
            state = "connected"
        elif ("igate server" in lowered or "aprs-is" in lowered) and any(
                word in lowered for word in ("failed", "closing connection", "lost", "unable", "error")):
            state = "disconnected"
    return state


# ------------------------------------------------------------------
# KISS and AX.25 decoding for the monitor in gateway.py
# ------------------------------------------------------------------

FEND, FESC, TFEND, TFESC = 0xC0, 0xDB, 0xDC, 0xDD
_GENERIC_DIGI = re.compile(r"^(WIDE|RELAY|TRACE|TCPIP|NOGATE|RFONLY)")


def kiss_frames(buffer: bytes) -> tuple[list[bytes], bytes]:
    """Split a KISS byte stream into unescaped data frames; returns (frames, unfinished rest)."""
    frames = []
    while True:
        start = buffer.find(bytes([FEND]))
        if start < 0:
            return frames, b""
        end = buffer.find(bytes([FEND]), start + 1)
        if end < 0:
            return frames, buffer[start:]
        raw, buffer = buffer[start + 1:end], buffer[end:]
        if len(raw) < 2 or raw[0] & 0x0F != 0:  # empty or not a data frame
            continue
        frame = bytearray()
        escaped = False
        for byte in raw[1:]:
            if escaped:
                frame.append(FEND if byte == TFEND else FESC if byte == TFESC else byte)
                escaped = False
            elif byte == FESC:
                escaped = True
            else:
                frame.append(byte)
        frames.append(bytes(frame))


def _address(chunk: bytes) -> tuple[str, int]:
    call = "".join(chr(byte >> 1) for byte in chunk[:6]).strip()
    ssid = (chunk[6] >> 1) & 0x0F
    return (f"{call}-{ssid}" if ssid else call), chunk[6]


def ax25_packet(frame: bytes) -> dict | None:
    """AX.25 UI frame -> source, destination, path (repeated digis marked *), info, heard_from."""
    addresses = []
    for offset in range(0, min(len(frame), 70), 7):
        chunk = frame[offset:offset + 7]
        if len(chunk) < 7:
            return None
        addresses.append(_address(chunk))
        if chunk[6] & 0x01:
            break
    else:
        return None
    body = frame[len(addresses) * 7:]
    if len(addresses) < 2 or len(body) < 2 or body[0] != 0x03 or body[1] != 0xF0:
        return None  # not a UI frame with "no layer 3" PID, i.e. not APRS
    (destination, _), (source, _) = addresses[0], addresses[1]
    path, heard_from = [], source
    for call, flags in addresses[2:]:
        repeated = bool(flags & 0x80)
        path.append(call + ("*" if repeated else ""))
        if repeated:
            heard_from = None if _GENERIC_DIGI.match(call) else call
    try:
        info = body[2:].decode("utf-8")
    except UnicodeDecodeError:
        info = body[2:].decode("latin-1")
    if not re.match(r"^[A-Z0-9-]{1,9}$", source) or not info:
        return None
    return {"source": source, "destination": destination, "path": ",".join(path),
            "info": info.rstrip("\r\n"), "heard_from": heard_from}


def tnc2(packet: dict) -> str:
    """Packet in the text form used by APRS-IS: SRC>DST,PATH:info."""
    path = f",{packet['path']}" if packet["path"] else ""
    return f"{packet['source']}>{packet['destination']}{path}:{packet['info']}"


def decode(packet: dict) -> dict:
    """Position, symbol and comment via aprslib; empty values when it cannot parse the packet."""
    result = {"packet_format": None, "latitude": None, "longitude": None,
              "symbol_table": None, "symbol": None, "comment": None}
    try:
        import aprslib
        parsed = aprslib.parse(tnc2(packet))
    except Exception:  # aprslib raises several own exception types on odd packets
        return result
    result["packet_format"] = str(parsed.get("format") or "")[:16] or None
    for key in ("latitude", "longitude"):
        value = parsed.get(key)
        result[key] = float(value) if isinstance(value, (int, float)) else None
    if result["latitude"] is not None and not (-90 <= result["latitude"] <= 90
                                               and -180 <= (result["longitude"] or 0) <= 180):
        result["latitude"] = result["longitude"] = None
    for key in ("symbol_table", "symbol"):
        value = parsed.get(key)
        result[key] = str(value)[:1] if value else None
    text = parsed.get("comment") or parsed.get("status") or parsed.get("message_text")
    result["comment"] = str(text)[:200] if text else None
    return result

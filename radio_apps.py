#!/usr/bin/env python3
"""
Start and stop the HF modem stack (rigctld, VARA, XARA, Mercury, VarAC) from the web UI.

Every program runs as a transient systemd *user* unit (systemd-run --user),
so it survives restarts of the web service and can be stopped cleanly with
its whole process tree. Wine programs share one persistent wineserver unit;
otherwise the wineserver would live inside the first program's unit and
stopping VARA would also kill VarAC.

Run `radio_apps.py autostart` from the desktop session (see
AUTOSTART_FILE) to start the programs enabled for autostart, each after its
configured delay.
"""

import functools
import getpass
import os
import re
import shlex
import shutil
import subprocess
import sys
import time

import common

UNIT_PREFIX = "meshcom-radio-"
WINESERVER_UNIT = f"{UNIT_PREFIX}wineserver.service"
AUTOSTART_FILE = os.path.join(os.path.expanduser("~"), ".config", "autostart", "meshcom-radio.desktop")
MAX_DELAY_SECONDS = 600
DEFAULT_MODEM_PORT = 8300
DEFAULT_MERCURY_GUI_PORT = 10088
VARA_PORT = 8300                 # VARA's own TCP port; set in VARA, not here
XARA_KISS_PORT = 8100
XARA_CONFIG_PATH = os.path.join(os.path.expanduser("~"), ".config", "xara", "xara.conf")
XARA_CONFIG_HEADER = "# Generated by the MeshCom gateway web (VarAC tab); overwritten on every XARA start."
XARA_MODES = {
    "hf500": ("hf", "500", "HF 500 Hz"),
    "hf2300": ("hf", "2300", "HF 2300 Hz"),
    "hf2750": ("hf", "2750", "HF 2750 Hz"),
    "fmnarrow": ("fm", "narrow", "FM narrow"),
    "fmwide": ("fm", "wide", "FM wide"),
}
XARA_PTT = {"rigctld": "CAT přes rigctld", "vox": "VOX"}
RIGCTLD_SPEEDS = (0, 4800, 9600, 19200, 38400, 57600, 115200)
# ALSA names and device paths: no spaces, quotes or newlines that could break the config file.
_DEVICE_NAME = re.compile(r"^[A-Za-z0-9_:=,.\-/]+$")
_CALLSIGN = re.compile(r"^[A-Z0-9]{3,8}(-[0-9]{1,2})?$")
# Ports >= 1024 that Chrome and Firefox refuse to open (ERR_UNSAFE_PORT, Fetch "bad port" list).
BROWSER_BLOCKED_PORTS = frozenset({1719, 1720, 1723, 2049, 3659, 4045, 4190, 5060, 5061, 6000, 6566,
                                   6665, 6666, 6667, 6668, 6669, 6679, 6697, 10080})

APPS = {
    "rigctld": {"label": "rigctld (CAT)", "kind": "native"},
    "vara": {"label": "VARA", "kind": "wine", "path_key": "radio_vara_path"},
    "xara": {"label": "XARA", "kind": "native"},
    "mercury": {"label": "Mercury", "kind": "native"},
    "varac": {"label": "VarAC", "kind": "wine", "path_key": "radio_varac_path"},
}
WINE_APPS = tuple(app for app, spec in APPS.items() if spec["kind"] == "wine")


class RadioError(RuntimeError):
    pass


def unit_name(app: str) -> str:
    if app not in APPS:
        raise RadioError(f"Neznámý program: {app}")
    return f"{UNIT_PREFIX}{app}.service"


def _user_env() -> dict:
    # The web UI runs as a system service without a session; point systemctl
    # at the user manager of the same account.
    env = dict(os.environ)
    if not hasattr(os, "getuid"):
        return env
    runtime_dir = f"/run/user/{os.getuid()}"
    env.setdefault("XDG_RUNTIME_DIR", runtime_dir)
    env.setdefault("DBUS_SESSION_BUS_ADDRESS", f"unix:path={runtime_dir}/bus")
    return env


def _run(arguments: list[str], check: bool = True, timeout: int = 20) -> subprocess.CompletedProcess:
    try:
        result = subprocess.run(
            arguments, check=False, capture_output=True, text=True,
            timeout=timeout, env=_user_env(),
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise RadioError(f"Příkaz {arguments[0]} se nepodařilo spustit: {exc}") from exc
    if check and result.returncode:
        detail = result.stderr.strip() or result.stdout.strip()
        if "Failed to connect to bus" in detail or "No medium found" in detail:
            detail = ("Uživatelský systemd neběží. Přihlaste se do desktopu nebo "
                      f"spusťte `sudo loginctl enable-linger {getpass.getuser()}`.")
        raise RadioError(detail or f"{arguments[0]} skončil s kódem {result.returncode}.")
    return result


def systemctl(*arguments: str, check: bool = True) -> subprocess.CompletedProcess:
    return _run(["systemctl", "--user", *arguments], check=check)


def _mercury_option(cfg: dict, flag: str, default: int) -> int:
    """Integer value of a Mercury option such as `-p 8400` or `-p8400`."""
    try:
        arguments = shlex.split(str(cfg.get("radio_mercury_args", "")))
    except ValueError:
        return default
    for index, argument in enumerate(arguments):
        value = None
        if argument == flag and index + 1 < len(arguments):
            value = arguments[index + 1]
        elif argument.startswith(flag) and len(argument) > 2:
            value = argument[2:]
        if value is not None:
            try:
                return int(value)
            except ValueError:
                return default
    return default


def mercury_port(cfg: dict) -> int:
    return _mercury_option(cfg, "-p", DEFAULT_MODEM_PORT)


def mercury_gui_port(cfg: dict) -> int:
    """WebSocket/HTTP port of the Mercury web GUI (-U overrides the setting)."""
    try:
        configured = int(cfg.get("radio_mercury_gui_port", DEFAULT_MERCURY_GUI_PORT))
    except (TypeError, ValueError):
        configured = DEFAULT_MERCURY_GUI_PORT
    if configured in BROWSER_BLOCKED_PORTS:
        configured = DEFAULT_MERCURY_GUI_PORT
    return _mercury_option(cfg, "-U", configured)


def _int(cfg: dict, key: str, default: int) -> int:
    try:
        return int(cfg.get(key, default))
    except (TypeError, ValueError):
        return default


def xara_port(cfg: dict) -> int:
    return _int(cfg, "xara_port", DEFAULT_MODEM_PORT)


def xara_ui_port(cfg: dict) -> int:
    """Port of the XARA web UI, 0 when it is off."""
    return _int(cfg, "xara_ui_port", 0)


def rigctld_port(cfg: dict) -> int:
    return _int(cfg, "rigctld_port", 4532)


def xara_call(cfg: dict) -> str:
    """Callsign for XARA: its own setting, else the gateway callsign without SSID."""
    call = str(cfg.get("xara_call", "")).strip().upper()
    return call or str(cfg.get("callsign", "")).strip().upper().split("-")[0]


def modem_ports(cfg: dict) -> dict[str, int]:
    """Command port of each modem; the data port is the next one."""
    return {"vara": VARA_PORT, "xara": xara_port(cfg), "mercury": mercury_port(cfg)}


def port_conflicts(cfg: dict, active: set) -> list[tuple[str, str, int]]:
    """Modem pairs whose command/data ports overlap and that would run together."""
    ports = modem_ports(cfg)
    names = list(ports)
    conflicts = []
    for index, first in enumerate(names):
        for second in names[index + 1:]:
            if abs(ports[first] - ports[second]) > 1:
                continue
            both_autostart = cfg.get(f"radio_{first}_autostart") and cfg.get(f"radio_{second}_autostart")
            if both_autostart or {first, second} <= active:
                conflicts.append((first, second, ports[first]))
    return conflicts


def _program(cfg: dict, app: str, name: str) -> str:
    command = str(cfg.get(f"radio_{app}_command", "")).strip() or name
    label = APPS[app]["label"]
    if os.path.basename(command) != name:
        raise RadioError(f"{label}: příkaz musí být program {name} nebo cesta k němu.")
    if shutil.which(command) is None:
        raise RadioError(f"{label}: program {command} nebyl nalezen.")
    return command


def xara_config_text(cfg: dict) -> str:
    """Contents of the XARA config file (key = value, see xara.conf.example)."""
    call = xara_call(cfg)
    if not _CALLSIGN.match(call):
        raise RadioError(f"XARA: neplatná volací značka {call or '(prázdná)'}.")
    mode = XARA_MODES.get(str(cfg.get("xara_mode", "")))
    if mode is None:
        raise RadioError("XARA: neznámý režim.")
    devices = {}
    for direction, label in (("capture", "vstup zvuku (příjem)"), ("playback", "výstup zvuku (vysílání)")):
        device = xara_audio_device(cfg, direction)
        if not device:
            raise RadioError(f"XARA: vyberte {label}.")
        if not _DEVICE_NAME.match(device):
            raise RadioError(f"XARA: neplatný název zvukového zařízení {device}.")
        devices[direction] = device
    ptt = str(cfg.get("xara_ptt", "rigctld"))
    if ptt not in XARA_PTT:
        raise RadioError("XARA: neznámý způsob PTT.")
    try:
        drive_db = float(cfg.get("xara_drive_db", -5))
    except (TypeError, ValueError):
        drive_db = -5.0
    lines = [
        XARA_CONFIG_HEADER,
        f"call = {call}",
        f"{mode[0]} = {mode[1]}",
        "audio = alsa",
        f"capture = {devices['capture']}",
        f"playback = {devices['playback']}",
        "radio",
        f"drive-db = {max(-40.0, min(0.0, drive_db)):g}",
        f"ptt = rigctld:127.0.0.1:{rigctld_port(cfg)}" if ptt == "rigctld" else "ptt = vox",
        "addr = 127.0.0.1",
        f"port = {xara_port(cfg)}",
        f"kiss-port = {XARA_KISS_PORT}",
    ]
    if xara_ui_port(cfg):
        # Read-only status page; without ui-control nobody can key the radio from it.
        lines += [f"ui-port = {xara_ui_port(cfg)}", "ui-addr = 0.0.0.0"]
    return "\n".join(lines) + "\n"


def write_xara_config(cfg: dict, path: str | None = None) -> str:
    """Write the XARA config; a hand-written file found there is kept as .bak first."""
    path = path or XARA_CONFIG_PATH
    text = xara_config_text(cfg)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path):
        with open(path, encoding="utf-8", errors="replace") as handle:
            if handle.readline().rstrip("\n") != XARA_CONFIG_HEADER:
                os.replace(path, path + ".bak")
    tmp_path = path + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp_path, path)
    return path


def rigctld_command(cfg: dict) -> list[str]:
    command = _program(cfg, "rigctld", "rigctld")
    model = _int(cfg, "rigctld_model", 0)
    if model <= 0:
        raise RadioError("rigctld: vyberte model rádia.")
    device = str(cfg.get("rigctld_device", "")).strip()
    if not device or not _DEVICE_NAME.match(device):
        raise RadioError("rigctld: vyberte sériový port rádia.")
    arguments = [command, "-m", str(model), "-r", device]
    speed = _int(cfg, "rigctld_speed", 0)
    if speed:
        arguments += ["-s", str(speed)]
    return arguments + ["-T", "127.0.0.1", "-t", str(rigctld_port(cfg))]


def xara_audio_device(cfg: dict, direction: str) -> str:
    """ALSA device for "capture" or "playback"; older configs had one shared xara_audio_device."""
    return (str(cfg.get(f"xara_{direction}_device", "")).strip()
            or str(cfg.get("xara_audio_device", "")).strip())


def _read(path: str) -> str:
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            return handle.read()
    except OSError:
        return ""


def sound_devices(cards_file: str = "/proc/asound/cards",
                  pcm_file: str = "/proc/asound/pcm") -> dict[str, list[dict]]:
    """ALSA capture and playback devices as stable plughw names, USB cards first.

    /proc/asound/pcm says which device of a card records and which plays
    ("02-00: USB Audio : USB Audio : playback 1 : capture 1").
    """
    cards = {}
    for match in re.finditer(r"^\s*(\d+)\s+\[(\S+)\s*\]:\s*(\S+)\s+-\s+(.*)$", _read(cards_file), re.MULTILINE):
        number, card_id, driver, name = match.groups()
        usb = driver.startswith("USB")
        cards[int(number)] = {"id": card_id, "usb": usb, "label": f"{name.strip()} ({'USB' if usb else driver})"}
    devices = {"capture": [], "playback": []}
    pcm = _read(pcm_file)
    for match in re.finditer(r"^(\d+)-(\d+):(.*)$", pcm, re.MULTILINE):
        card = cards.get(int(match.group(1)))
        if card is None:
            continue
        device = int(match.group(2))
        for direction in devices:
            if re.search(rf":\s*{direction}\s+\d+", match.group(3)):
                devices[direction].append({
                    "value": f"plughw:CARD={card['id']},DEV={device}", "usb": card["usb"],
                    "label": card["label"] + (f", zařízení {device}" if device else "")})
    if not pcm:  # no pcm list: offer device 0 of every card both ways
        for card in cards.values():
            for direction in devices:
                devices[direction].append({"value": f"plughw:CARD={card['id']},DEV=0",
                                           "usb": card["usb"], "label": card["label"]})
    return {direction: sorted(items, key=lambda item: not item["usb"]) for direction, items in devices.items()}


def serial_devices(by_id_dir: str = "/dev/serial/by-id") -> list[str]:
    """Stable serial port names (they survive reboots, unlike /dev/ttyUSBn)."""
    try:
        return sorted(os.path.join(by_id_dir, name) for name in os.listdir(by_id_dir))
    except OSError:
        return []


@functools.lru_cache(maxsize=1)
def rig_models() -> tuple[tuple[int, str], ...]:
    """(model number, "Maker Model") from `rigctl -l`; empty without hamlib."""
    if shutil.which("rigctl") is None:
        return ()
    try:
        output = subprocess.run(["rigctl", "-l"], capture_output=True, text=True, timeout=10).stdout
    except (OSError, subprocess.TimeoutExpired):
        return ()
    models = []
    for line in output.splitlines():
        # " 3073  Icom                   IC-7300                 20210128.0      Stable      RIG_MODEL_IC7300"
        match = re.match(r"^\s*(\d+)\s+(.+?)\s{2,}(.+?)\s{2,}", line)
        if match:
            models.append((int(match.group(1)), f"{match.group(2)} {match.group(3)}"))
    return tuple(models)


def app_command(app: str, cfg: dict) -> list[str]:
    spec = APPS[app]
    if spec["kind"] == "wine":
        path = str(cfg.get(spec["path_key"], "")).strip()
        if not path.lower().endswith(".exe"):
            raise RadioError(f"{spec['label']}: cesta musí končit na .exe.")
        if not os.path.isfile(path):
            raise RadioError(f"{spec['label']}: soubor {path} neexistuje.")
        return ["wine", path]
    if app == "rigctld":
        return rigctld_command(cfg)
    if app == "xara":
        command = _program(cfg, "xara", "xara")
        try:
            path = write_xara_config(cfg)
        except OSError as exc:
            raise RadioError(f"XARA: konfiguraci se nepodařilo zapsat: {exc}") from exc
        return [command, "--config", path]

    command = _program(cfg, "mercury", "mercury")
    try:
        arguments = shlex.split(str(cfg.get("radio_mercury_args", "")))
    except ValueError as exc:
        raise RadioError(f"Mercury: neplatné parametry: {exc}") from exc
    if cfg.get("radio_mercury_gui"):
        # -G serves the built-in web GUI (spectrum, waterfall, status) and
        # its WebSocket on the -U port.
        if "-G" not in arguments:
            arguments.append("-G")
        if not any(argument.startswith("-U") for argument in arguments):
            arguments += ["-U", str(mercury_gui_port(cfg))]
        if cfg.get("radio_mercury_no_waterfall") and "-W" not in arguments:
            arguments.append("-W")
    return [command, *arguments]


def _environment(cfg: dict) -> list[str]:
    home = os.path.expanduser("~")
    values = {
        "WINEPREFIX": str(cfg.get("radio_wine_prefix", "")).strip() or os.path.join(home, ".wine"),
        "WINEDEBUG": "-all",
        "BOX86_DYNAREC_BIGBLOCK": "0",
        "BOX64_DYNAREC_STRONGMEM": "1",
        "MESA_GL_VERSION_OVERRIDE": "3.2",
    }
    display = str(cfg.get("radio_display", "")).strip()
    if display:
        values["DISPLAY"] = display
    xauthority = os.path.join(home, ".Xauthority")
    if os.path.isfile(xauthority):
        values["XAUTHORITY"] = xauthority
    return [f"{key}={value}" for key, value in values.items()]


def _launch(unit: str, description: str, command: list[str], cfg: dict) -> None:
    systemctl("reset-failed", unit, check=False)
    arguments = ["systemd-run", "--user", "--collect", f"--unit={unit}",
                 f"--description={description}"]
    for item in _environment(cfg):
        arguments.append(f"--setenv={item}")
    _run([*arguments, "--", *command])


def is_active(unit: str) -> bool:
    return systemctl("is-active", "--quiet", unit, check=False).returncode == 0


def _ensure_wineserver(cfg: dict) -> None:
    if is_active(WINESERVER_UNIT) or shutil.which("wineserver") is None:
        return
    _launch(WINESERVER_UNIT, "MeshCom shared wineserver",
            ["wineserver", "--foreground", "--persistent"], cfg)
    time.sleep(1)


def unit_status(unit: str) -> dict:
    result = {"state": "unknown", "sub_state": "", "since": "", "enabled": "", "error": None}
    try:
        output = systemctl(
            "show", unit, "--property=ActiveState,SubState,ActiveEnterTimestamp,UnitFileState",
        ).stdout
    except RadioError as exc:
        result["error"] = str(exc)
        return result
    properties = dict(line.split("=", 1) for line in output.splitlines() if "=" in line)
    result["state"] = properties.get("ActiveState", "unknown")
    result["sub_state"] = properties.get("SubState", "")
    result["enabled"] = properties.get("UnitFileState", "")
    if result["state"] == "active":
        result["since"] = properties.get("ActiveEnterTimestamp", "")
    return result


def status(app: str) -> dict:
    return unit_status(unit_name(app))


def start(app: str, cfg: dict | None = None) -> bool:
    """Start the program; returns False if it was already running."""
    cfg = cfg or common.load_config()
    unit = unit_name(app)
    if is_active(unit):
        return False
    command = app_command(app, cfg)
    if APPS[app]["kind"] == "wine":
        _ensure_wineserver(cfg)
    _launch(unit, f"MeshCom {APPS[app]['label']}", command, cfg)
    return True


def stop(app: str) -> None:
    systemctl("stop", unit_name(app))
    if APPS[app]["kind"] == "wine" and not any(is_active(unit_name(item)) for item in WINE_APPS):
        systemctl("stop", WINESERVER_UNIT, check=False)


def restart(app: str, cfg: dict | None = None) -> None:
    stop(app)
    start(app, cfg)


JOURNAL_HINT = ("Výpis není dostupný: journal je jen v RAM a logy uživatelských služeb jsou v systémovém "
                "journalu. Přidejte účet do skupiny systemd-journal (`sudo usermod -aG systemd-journal "
                "{user}`, pak restart webu), nebo zapněte trvalý journal (INSTALL, kapitola 9.2).")


def unit_log(unit: str, lines: int = 15) -> str:
    """Newest journal lines of a user unit.

    `--user-unit` also finds the lines when the journal is volatile and user
    units log into the system journal, where `journalctl --user` sees nothing.
    """
    options = ["-n", str(lines), "--no-pager", "-o", "short-iso"]
    hint = False
    for arguments in (["journalctl", f"--user-unit={unit}", *options],
                      ["journalctl", "--user", "-u", unit, *options]):
        try:
            result = _run(arguments, check=False)
        except RadioError:
            return ""
        output = result.stdout.strip()
        if output and output != "-- No entries --":
            return output
        hint = hint or "not seeing messages" in result.stderr
    return JOURNAL_HINT.format(user=getpass.getuser()) if hint else ""


def recent_log(app: str, lines: int = 15) -> str:
    return unit_log(unit_name(app), lines)


def autostart_plan(cfg: dict) -> list[tuple[int, str]]:
    plan = []
    for app in APPS:
        if cfg.get(f"radio_{app}_autostart"):
            try:
                delay = int(cfg.get(f"radio_{app}_delay", 0))
            except (TypeError, ValueError):
                delay = 0
            plan.append((max(0, min(delay, MAX_DELAY_SECONDS)), app))
    return sorted(plan, key=lambda item: (item[0], list(APPS).index(item[1])))


def _desktop_quote(argument: str) -> str:
    # Desktop Entry Exec keys accept only double quotes with these escapes.
    escaped = "".join(f"\\{char}" if char in '"`$\\' else char for char in argument)
    return f'"{escaped}"'


def sync_autostart_entry(cfg: dict) -> bool:
    """Create or remove the desktop autostart entry; returns True if present."""
    if not autostart_plan(cfg):
        if os.path.exists(AUTOSTART_FILE):
            os.remove(AUTOSTART_FILE)
        return False

    script = os.path.abspath(__file__)
    content = (
        "[Desktop Entry]\n"
        "Type=Application\n"
        "Name=MeshCom HF modems and VarAC\n"
        "Comment=Starts the HF modem programs enabled in the MeshCom web UI\n"
        f"Exec={_desktop_quote(sys.executable)} {_desktop_quote(script)} autostart\n"
        "X-GNOME-Autostart-enabled=true\n"
    )
    os.makedirs(os.path.dirname(AUTOSTART_FILE), exist_ok=True)
    tmp_path = AUTOSTART_FILE + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as handle:
        handle.write(content)
    os.replace(tmp_path, AUTOSTART_FILE)
    return True


def run_autostart(cfg: dict | None = None, sleep=time.sleep, clock=time.monotonic) -> None:
    cfg = cfg or common.load_config()
    session_vars = [name for name in ("DISPLAY", "XAUTHORITY", "WAYLAND_DISPLAY") if os.environ.get(name)]
    if session_vars:
        systemctl("import-environment", *session_vars, check=False)

    started_at = clock()
    for delay, app in autostart_plan(cfg):
        remaining = started_at + delay - clock()
        if remaining > 0:
            sleep(remaining)
        try:
            started = start(app, cfg)
            print(f"{APPS[app]['label']}: {'spuštěno' if started else 'již běží'}", flush=True)
        except RadioError as exc:
            print(f"{APPS[app]['label']}: {exc}", file=sys.stderr, flush=True)


if __name__ == "__main__":
    if sys.argv[1:] != ["autostart"]:
        sys.exit(f"Použití: {sys.argv[0]} autostart")
    run_autostart()

"""
Generate LinBPQ's bpq32.cfg from the BPQ tab: node, Telnet/web port with the
sysop user, one KISS-over-TCP port per enabled LoRa TNC and the BBS.

Keywords follow the G8BPQ documentation (BPQCFGFile.html, TelnetServer.htm,
KISS.html). The sysop password is never stored in config.json; it lives only
in bpq32.cfg (mode 0600). Leaving the password field empty keeps the one
already in the file.
"""

import ipaddress
import os
import re
import time

import bpq_services
from radio_apps import RadioError

CONFIG_NAME = "bpq32.cfg"
HEADER = "; Generated by the MeshCom gateway web UI (BPQ tab). Manual edits are overwritten;"
CALLSIGN = re.compile(r"(?=[A-Z0-9]*[0-9])[A-Z0-9]{3,6}(?:-(?:1[0-5]|[0-9]))?")
ALIAS = re.compile(r"[A-Z0-9]{1,6}")
LOCATOR = re.compile(r"[A-R]{2}[0-9]{2}(?:[A-X]{2})?")
USERNAME = re.compile(r"[A-Za-z0-9_.-]{1,20}")
MAX_TEXT_LINES = 10
MAX_TEXT_LINE = 200
# (key suffix, label, minimum, maximum) of the AX.25 link settings per TNC port.
AX25_FIELDS = (
    ("paclen", "PACLEN", 32, 256),
    ("maxframe", "MAXFRAME", 1, 7),
    ("frack", "FRACK (ms)", 1000, 60000),
    ("resptime", "RESPTIME (ms)", 0, 10000),
    ("retries", "RETRIES", 1, 20),
)
AX25_KEYWORDS = {"paclen": "PACLEN", "maxframe": "MAXFRAME", "frack": "FRACK",
                 "resptime": "RESPTIME", "retries": "RETRIES"}


def config_path(cfg: dict) -> str:
    return os.path.join(os.path.dirname(str(cfg.get("linbpq_path", "")).strip()), CONFIG_NAME)


def _text_block(raw: str, label: str) -> list[str]:
    lines = [line.rstrip() for line in str(raw).replace("\r", "").split("\n")]
    while lines and not lines[-1]:
        lines.pop()
    if len(lines) > MAX_TEXT_LINES:
        raise RadioError(f"{label}: nejvýše {MAX_TEXT_LINES} řádků.")
    for line in lines:
        if line.strip() == "***" or len(line) > MAX_TEXT_LINE or any(ord(c) < 32 for c in line):
            raise RadioError(f"{label}: řádek nesmí být „***“, delší než {MAX_TEXT_LINE} znaků ani obsahovat řídicí znaky.")
    return lines


def _number(cfg: dict, key: str, label: str, minimum: int, maximum: int) -> int:
    try:
        value = int(str(cfg.get(key, "")).strip())
    except ValueError:
        raise RadioError(f"{label} musí být celé číslo.") from None
    if not minimum <= value <= maximum:
        raise RadioError(f"{label} musí být {minimum} až {maximum}.")
    return value


def existing_password(path: str, user: str) -> str | None:
    """Password of `user` from an existing bpq32.cfg (USER=name,password,...)."""
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            for line in handle:
                line = line.split(";", 1)[0].strip()
                if line.upper().startswith("USER="):
                    fields = line[5:].split(",")
                    if len(fields) > 1 and fields[0].strip() == user:
                        return fields[1].strip() or None
    except OSError:
        return None
    return None


def settings(cfg: dict) -> dict:
    """Validated node settings; raises RadioError with the first problem."""
    nodecall = str(cfg.get("bpq_nodecall", "")).strip().upper()
    if not CALLSIGN.fullmatch(nodecall):
        raise RadioError("Značka uzlu: zadejte volací znak se SSID, např. OK2ZAW-7.")
    nodealias = str(cfg.get("bpq_nodealias", "")).strip().upper()
    if not ALIAS.fullmatch(nodealias):
        raise RadioError("Alias uzlu: 1 až 6 písmen nebo číslic.")
    locator = str(cfg.get("bpq_locator", "")).strip().upper()
    if locator and not LOCATOR.fullmatch(locator):
        raise RadioError("Lokátor: 4 nebo 6 znaků, např. JN89AA.")
    user = str(cfg.get("bpq_sysop_user", "")).strip()
    if not USERNAME.fullmatch(user):
        raise RadioError("Uživatel sysop: 1 až 20 znaků (písmena, číslice, _ . -).")
    sysop_call = str(cfg.get("bpq_sysop_call", "")).strip().upper() or nodecall.split("-")[0]
    if not CALLSIGN.fullmatch(sysop_call):
        raise RadioError("Značka sysopa: zadejte volací znak, např. OK2ZAW.")
    localnet = str(cfg.get("bpq_localnet", "")).strip()
    if localnet:
        try:
            localnet = str(ipaddress.IPv4Network(localnet, strict=False))
        except ValueError:
            raise RadioError("Místní síť: zadejte rozsah IPv4, např. 192.168.99.0/24.") from None
    telnet_port = _number(cfg, "bpq_telnet_port", "Telnet port", 1024, 65535)
    http_port = _number(cfg, "linbpq_web_port", "Port webu LinBPQ", 1024, 65535)
    ports = []
    for tnc in bpq_services.TNCS:
        if not bpq_services.is_enabled(tnc, cfg):
            continue
        label = bpq_services.SERVICES[tnc]["label"]
        port = {"tnc": tnc, "label": label,
                "tcp_port": _number(cfg, f"{tnc}_tcp_port", f"{label}: KISS TCP port", 1024, 65535)}
        for suffix, field_label, minimum, maximum in AX25_FIELDS:
            port[suffix] = _number(cfg, f"{tnc}_{suffix}", f"{label}: {field_label}", minimum, maximum)
        ports.append(port)
    used = [telnet_port, http_port, *(port["tcp_port"] for port in ports)]
    if len(set(used)) != len(used):
        raise RadioError("Telnet port, port webu LinBPQ a KISS porty TNC se nesmí shodovat.")
    bbs = bool(cfg.get("bpq_bbs_enabled"))
    bbs_call = str(cfg.get("bpq_bbs_call", "")).strip().upper()
    bbs_alias = str(cfg.get("bpq_bbs_alias", "")).strip().upper()
    if bbs:
        if not CALLSIGN.fullmatch(bbs_call) or bbs_call == nodecall:
            raise RadioError("Značka BBS: volací znak s jiným SSID než uzel, např. OK2ZAW-1.")
        if not ALIAS.fullmatch(bbs_alias) or bbs_alias == nodealias:
            raise RadioError("Alias BBS: 1 až 6 písmen nebo číslic, jiný než alias uzlu.")
    return {
        "nodecall": nodecall, "nodealias": nodealias, "locator": locator,
        "info": _text_block(cfg.get("bpq_info", ""), "Informační text"),
        "ctext": _text_block(cfg.get("bpq_ctext", ""), "Uvítací text"),
        "user": user, "sysop_call": sysop_call, "localnet": localnet,
        "telnet_port": telnet_port, "http_port": http_port, "ports": ports,
        "bbs": bbs, "bbs_call": bbs_call, "bbs_alias": bbs_alias,
    }


def check_password(password: str) -> str:
    password = str(password)
    if len(password) < 6 or any(c in password for c in ",;") or any(c.isspace() for c in password):
        raise RadioError("Heslo sysopa: aspoň 6 znaků, bez mezer, čárky a středníku.")
    return password


def render(cfg: dict, password: str) -> str:
    node = settings(cfg)
    lines = [
        HEADER,
        "; the previous version is kept as bpq32.cfg.bak-<date>.",
        "",
        "SIMPLE",
        f"NODECALL={node['nodecall']}",
        f"NODEALIAS={node['nodealias']}",
    ]
    if node["locator"]:
        lines.append(f"LOCATOR={node['locator']}")
    lines += ["NODE=1", "BBS=1", ""]
    if node["info"]:
        lines += ["INFOMSG:", *node["info"], "***", ""]
    if node["ctext"]:
        lines += ["CTEXT:", *node["ctext"], "***", ""]
    lines += [
        "PORT",
        " PORTNUM=1",
        " ID=Telnet a web",
        " DRIVER=TELNET",
        " CONFIG",
        "  LOGGING=1",
        "  DisconnectOnClose=1",
        f"  TCPPORT={node['telnet_port']}",
        f"  HTTPPORT={node['http_port']}",
        "  MAXSESSIONS=10",
    ]
    if node["localnet"]:
        lines.append(f"  LOCALNET={node['localnet']}")
    lines += [f"  USER={node['user']},{check_password(password)},{node['sysop_call']},,SYSOP", "ENDPORT", ""]
    for number, port in enumerate(node["ports"], start=2):
        lines += [
            "PORT",
            f" PORTNUM={number}",
            f" ID=LoRa {port['label']}",
            " TYPE=ASYNC",
            " PROTOCOL=KISS",
            " IPADDR=127.0.0.1",
            f" TCPPORT={port['tcp_port']}",
            *(f" {keyword}={port[suffix]}" for suffix, keyword in AX25_KEYWORDS.items()),
            "ENDPORT",
            "",
        ]
    if node["bbs"]:
        lines += [f"APPLICATION 1,BBS,,{node['bbs_call']},{node['bbs_alias']},255", "LINMAIL", ""]
    return "\n".join(lines)


def preview(cfg: dict) -> str:
    """The file as it would be written, with the password masked."""
    return render(cfg, "********")


def write(cfg: dict, password: str = "") -> tuple[str, str | None]:
    """Write bpq32.cfg; returns (path, backup path or None). Empty password keeps the current one."""
    path = config_path(cfg)
    if not os.path.isdir(os.path.dirname(path)):
        raise RadioError(f"Adresář {os.path.dirname(path)} neexistuje; nejdřív nainstalujte LinBPQ (12.3).")
    node = settings(cfg)
    if not password:
        password = existing_password(path, node["user"])
        if not password:
            raise RadioError(f"Zadejte heslo sysopa; v {path} zatím žádné pro uživatele {node['user']} není.")
    content = render(cfg, password)
    backup = None
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            current = handle.read()
    except FileNotFoundError:
        current = None
    if current == content:
        return path, None
    tmp_path = path + ".tmp"
    fd = os.open(tmp_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(content)
    os.chmod(tmp_path, 0o600)
    if current is not None:
        backup = f"{path}.bak-{time.strftime('%Y%m%d-%H%M%S')}"
        os.replace(path, backup)
        os.chmod(backup, 0o600)  # the old file may hold a password too
    os.replace(tmp_path, path)
    return path, backup
